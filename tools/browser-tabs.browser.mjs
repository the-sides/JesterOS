import fs from 'node:fs/promises';
const profiles = ['macos-high-sierra-10.13', 'macos-mojave-10.14', 'macos-sonoma-14.0', 'macos-golden-gate-27.0.1', 'windows11-23h2-22631.2428'];

export async function runBrowserTabsAcceptance({ browser, baseURL, artifactDirectory }) {
  await fs.mkdir(artifactDirectory, { recursive: true });
  const reports = [];
  for (const profileId of profiles) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.setDefaultTimeout(8000);
    const report = { profileId, checks: [], errors: [], external: [] };
    reports.push(report);
    page.on('pageerror', e => report.errors.push(e.message));
    page.on('request', r => { if (!r.url().startsWith(new URL(baseURL).origin + '/') && !/^(data:|blob:)/.test(r.url())) report.external.push(r.url()); });
    const check = (ok, label) => { if (!ok) throw Error(label); report.checks.push(label); };
    const execute = (suffix, target, payload = {}) => page.evaluate(({ suffix, target, payload }) => jesteros.execute({ command: `browser.${suffix}`, target, payload }), { suffix, target, payload });
    const state = () => page.evaluate(() => jesteros.inspect().state.browser);
    const root = id => page.locator(`[data-browser-window-id="${id}"]`).filter({ visible: true });
    const c = (id, name) => root(id).locator(`[data-browser-control=${JSON.stringify(name)}]`);
    const windowData = async id => (await state()).windows.find(w => w.id === id);
    const currentTarget = async id => ({ windowId: id, tabId: (await windowData(id)).activeTabId });
    try {
      await page.goto(`${baseURL}/?profile=${profileId}`);
      await page.waitForFunction(() => window.jesteros?.inspect().state.windows.length);
      const appId = profileId.startsWith('windows') ? 'edge' : 'safari';
      await page.evaluate(appId => jesteros.execute({ command: 'app.open', target: { appId } }), appId);
      const original = (await state()).windows.find(w => !w.closed), id = original.id;
      await c(id, 'address').waitFor();
      await c(id, 'tab-new').click();
      await page.waitForFunction(id => jesteros.inspect().state.browser.windows.find(w => w.id === id).tabs.length === 2, id);
      check((await windowData(id)).tabs.length === 2, 'native New Tab creates independent record');
      await page.waitForFunction(id => document.activeElement?.dataset.browserControl === 'address' && document.activeElement.closest('[data-browser-window-id]')?.dataset.browserWindowId === id, id);
      check(await c(id, 'address').evaluate(n => n.selectionStart === 0 && n.selectionEnd === n.value.length), 'new tab address is focused and selected');
      const second = (await windowData(id)).activeTabId;
      check(second !== original.activeTabId, 'new tab has distinct identity');
      check((await execute('navigate', { windowId: id, tabId: second }, { address: 'jester://journal' })).status === 'applied', 'new tab navigates through canonical API');
      await c(id, `tab:${original.activeTabId}`).click();
      check((await windowData(id)).activeTabId === original.activeTabId, 'pointer selects original tab');
      check((await windowData(id)).tabs[0].entries[0].pageId === 'home', 'other tab navigation leaves original page unchanged');
      await c(id, 'panel-overview').click();
      await c(id, `overview-pin:${second}`).click();
      check((await windowData(id)).tabs[0].id === second && (await windowData(id)).tabs[0].pinned, 'overview pin moves original tab to pinned section');
      check(await c(id, `overview-close:${second}`).isDisabled(), 'pinned close follows declared unpin-first policy');
      const pinnedBefore = await state();
      check((await execute('tab.close', { windowId: id, tabId: second })).status === 'rejected', 'direct pinned close rejects');
      check(JSON.stringify(await state()) === JSON.stringify(pinnedBefore), 'rejected pinned close leaves graph unchanged');
      await c(id, `overview-pin:${second}`).click();
      await c(id, `overview-select:${second}`).click();
      check((await windowData(id)).activeTabId === second, 'overview selection returns actual tab');
      await c(id, `tab-close:${second}`).click();
      check((await windowData(id)).tabs.length === 1, 'native Close removes selected tab');
      await c(id, 'panel-overview').click();
      await c(id, 'tab-reopen-overview').click();
      check((await windowData(id)).activeTabId === second, 'Reopen restores original closed tab identity');
      check((await windowData(id)).tabs.find(t => t.id === second).entries.at(-1).pageId === 'journal', 'Reopen preserves real journal history');
      await c(id, 'address').click();
      await page.keyboard.press('Control+Tab');
      check((await windowData(id)).activeTabId === original.activeTabId, 'delivered Control-Tab cycles actual tabs');
      const ordinary = await execute('window.new', { windowId: id }, { private: false });
      check(ordinary.status === 'applied' && ordinary.windowId !== id, 'New Window allocates a separate managed window');
      const otherId = ordinary.windowId;
      await c(otherId, 'address').waitFor();
      check((await windowData(id)).tabs.length === 2, 'new window preserves source tab collection');
      await execute('window.close', { windowId: id });
      check((await windowData(id)).closed, 'Close retains ordinary browser model');
      await c(otherId, 'panel-overview').click();
      await c(otherId, 'window-reopen-overview').click();
      await c(id, 'address').waitFor();
      check(!(await windowData(id)).closed && (await windowData(id)).tabs.length === 2, 'explicit Reopen Last Closed Window restores full original tab set');
      const privateResult = await execute('window.new', { windowId: id }, { private: true });
      check(privateResult.status === 'applied', 'private window creation applies');
      const privateId = privateResult.windowId;
      await c(privateId, 'address').waitFor();
      check((await windowData(privateId)).private, 'private flag belongs to genuine private Root');
      const history = (await state()).history.length;
      await execute('navigate', await currentTarget(privateId), { address: 'jester://studio' });
      check((await state()).history.length === history, 'private navigation adds no ordinary history');
      await execute('tab.new', { windowId: privateId });
      const privateTab = await currentTarget(privateId);
      await execute('tab.close', privateTab);
      check(!(await state()).closedTabs.some(r => r.windowId === privateId), 'private closed tabs are not retained');
      await execute('window.close', { windowId: privateId });
      check(!(await state()).windows.some(w => w.id === privateId), 'private close discards private browser graph');
      const closedPrivate = await execute('window.focus', { windowId: privateId });
      check(closedPrivate.status === 'rejected', 'retired private Root cannot receive commands');
      await execute('window.focus', { windowId: id });
      await page.setViewportSize({ width: 390, height: 844 });
      check(await c(id, 'tab-new').isVisible(), 'tab creation remains present at narrow viewport');
      await page.screenshot({ path: `${artifactDirectory}/${profileId}-narrow.png` });
      await page.setViewportSize({ width: 1440, height: 1000 });
      await page.screenshot({ path: `${artifactDirectory}/${profileId}.png` });
      check(report.errors.length === 0, 'no page errors');
      check(report.external.length === 0, 'no external requests');
    } catch (error) { report.failure = error.stack; }
    finally { await context.close(); }
  }
  await fs.writeFile(`${artifactDirectory}/results.json`, JSON.stringify(reports, null, 2));
  if (reports.some(r => r.failure)) throw Error(JSON.stringify(reports, null, 2));
  return reports;
}
